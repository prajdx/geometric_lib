def area(a):
    '''
    Функция для вычисления площади квадрата:
        На вход принимает значение стороны квадрата (a)
        Вычисляет площадь по формуле S = a^2
    '''
    return a * a


def perimeter(a):
    '''
    Функция для вычисления периметра квадрата:
        На вход принимает значение стороны квадрата (a)
        Вычисляет периметр по формуле P = 4 * a
    '''
    return 4 * a